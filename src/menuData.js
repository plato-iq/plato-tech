function getMenuBySlug(slug) {
  return menus[slug] || [];
}

function getAvailableItems(slug) {
  const menu = getMenuBySlug(slug);

  return menu.map((category) => ({
    ...category,
    items: category.items.filter((item) => item.available),
  }));
}

